const { spawn } = require('node:child_process');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
(async () => {
  const child = spawn('python', [path.join(__dirname, 'server_fixture.py')], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
  let logs = ''; child.stderr.on('data', data => { logs += data; });
  const fixture = await new Promise((resolve, reject) => {
    let text = ''; const timer = setTimeout(() => reject(new Error('Fixture server did not start: ' + logs)), 20000);
    child.stdout.on('data', chunk => { text += chunk; if (text.includes('\n')) { clearTimeout(timer); try { resolve(JSON.parse(text.split('\n')[0])); } catch (error) { reject(error); } } });
    child.on('exit', code => { clearTimeout(timer); reject(new Error('Fixture server exited: ' + code + ' ' + logs)); });
  });
  const base = 'http://127.0.0.1:' + fixture.port;
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-proxy-server'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1500, height: 1050 } });
    await context.route('**/*', route => route.request().url().startsWith(base + '/') ? route.continue() : route.abort());
    await context.addInitScript(() => { window.WebSocket = class { close() {} }; });
    const page = await context.newPage(), errors = [];
    page.setDefaultTimeout(15000); page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/CRAWLER/', { waitUntil: 'domcontentloaded' });
    await page.locator('#open-workspace').click();
    await page.waitForFunction(() => window.CrawlerServer?.connected && window.CrawlerIntelligence.documents.size === 3);
    await page.waitForSelector('.signal-card');
    assert.equal(await page.locator('.rail-link').count(), 3);
    assert.match(await page.locator('#backend-state').innerText(), /connected/);
    await page.locator('.signal-title').filter({ hasText: 'NVIDIA' }).first().click();
    await page.waitForSelector('#server-dossier .auto-claim', { state: 'attached' });
    assert.match(await page.locator('#server-dossier').innerText(), /Extracted claims/);
    await page.locator('#server-dossier details').filter({ hasText: 'Extracted claims & contradictions' }).locator('summary').first().click();
    await page.locator('[data-server-review]').first().click();
    await page.locator('#server-review-form [name=status]').selectOption('Verified');
    await page.locator('#server-review-form [name=rationale]').fill('The direct original record was checked for this exact statement.');
    await page.locator('#server-review-form [data-server-evidence]').first().selectOption('supports');
    await page.locator('#server-review-form [name=directEvidenceReviewed]').check();
    await page.locator('#server-review-form button').click();
    await page.waitForFunction(() => !document.querySelector('#research-tools').open);
    await page.waitForFunction(() => window.CrawlerServer.cachedDossier(window.IntelligenceUI.selectedSignal())?.claims.some(c => c.status === 'Verified'));
    await page.locator('#research-detail [data-save]').click();
    await page.locator('#research-query').fill('What NVIDIA semiconductor developments should I watch?');
    await page.locator('#research-question button[type=submit]').click();
    await page.waitForSelector('#research-chat .chat-result');
    assert.match(await page.locator('#assistant-panel').innerText(), /Fixture/);
    await page.locator('[data-destination=watchlist]').click();
    await page.locator('#alert-form [name=query]').fill('NVIDIA');
    await page.locator('#alert-form [name=minMomentum]').fill('0');
    await page.locator('#alert-form button').click();
    await page.waitForFunction(() => window.CrawlerServer.workspace?.monitors.length === 1);
    await page.locator('#generate-brief').click();
    await page.waitForSelector('#research-tools[open]');
    assert.match(await page.locator('#tool-content').innerText(), /NVIDIA/);
    await page.locator('#close-tools').click();
    await page.locator('#brief-schedule-form button').click();
    await page.waitForFunction(() => window.CrawlerServer.workspace?.schedules.length === 1);
    await page.locator('[data-destination=operations]').click();
    await page.waitForSelector('#configure-connector');
    await page.locator('#configure-connector').click();
    await page.locator('#connector-tool-form [name=name]').fill('Fixture extra feed');
    await page.locator('#connector-tool-form [name=url]').fill('https://extra.example/feed');
    await page.locator('#connector-tool-form [name=permissions]').fill('Isolated fixture; polling is paused.');
    await page.locator('#connector-tool-form button').click();
    await page.waitForFunction(() => window.CrawlerServer.sources.length === 3);
    await page.locator('#historical-replay').click();
    await page.locator('#replay-tool-form [name=at]').fill(new Date(Date.now() - 864e5).toISOString().slice(0, 16));
    await page.locator('#replay-tool-form button').click();
    await page.waitForFunction(() => document.querySelector('#replay-output').textContent.includes('0 visible record'));
    await page.locator('#close-tools').click();
    await page.locator('[data-destination=overview]').click();
    await page.locator('.signal-title').filter({ hasText: 'NVIDIA' }).first().click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(process.env.TEMP || '.', 'crawler-server-overview.png'), fullPage: true });
    await page.evaluate(async () => { await window.CrawlerServer.pull(); await window.CrawlerServer.pull(); });
    const versions = await page.evaluate(async id => (await fetch('/api/document-versions?id=' + id).then(r => r.json())).versions.length, fixture.documentId);
    assert.equal(versions, 1, 'Polling the bridge must not create synthetic revisions');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: path.join(process.env.TEMP || '.', 'crawler-server-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Server browser integration passed: sync, extracted claims, reviewed evidence, research citations, monitors, briefs, connector configuration, replay, revision deduplication, and mobile layout.');
  } finally { await browser.close(); child.kill(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
