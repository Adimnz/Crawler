const {spawn}=require('node:child_process');
const path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const pause=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const child=spawn('python',[path.join(__dirname,'source_fixture.py')],{windowsHide:true,stdio:['pipe','pipe','pipe']});
  let browser,logs='';child.stderr.on('data',d=>{logs+=d;});
  try{
    const fixture=await new Promise((resolve,reject)=>{
      let out='';const t=setTimeout(()=>reject(new Error(logs||'Fixture startup timeout')),60000);
      child.stdout.on('data',d=>{out+=d;if(out.includes('\n')){clearTimeout(t);resolve(JSON.parse(out.split('\n')[0]));}});
      child.on('exit',()=>{clearTimeout(t);reject(new Error(logs));});
    });
    const base='http://127.0.0.1:'+fixture.port;
    browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-proxy-server']});
    const context=await browser.newContext({viewport:{width:1440,height:1000}});
    await context.route('**/*',r=>r.request().url().startsWith(base+'/')?r.continue():r.abort());
    await context.addInitScript(()=>{window.WebSocket=class{close(){}};});
    const page=await context.newPage(),errors=[],requests=[];
    page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(new URL(r.url()).pathname));
    await page.goto(base+'/CRAWLER/',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>window.CrawlerServer?.connected);
    await pause(400);
    assert.equal(requests.includes('/api/sources'),false,'Landing page must not load directory until opened');
    await page.locator('[data-open-source-directory]:visible').first().click();
    await page.waitForSelector('.source-card');
    assert.equal(await page.locator('.source-card').count(),12,'Directory should render a bounded page');
    await page.locator('[data-source-more]').click();
    assert.equal(await page.locator('.source-card').count(),22);
    await page.locator('#source-role').selectOption('discovery');
    assert.equal(await page.locator('.source-card').count(),1);
    await page.locator('[data-source-preview="source-1"]').click();
    await page.waitForFunction(()=>document.querySelector('#source-preview').textContent.includes('Research lead'));
    await page.locator('#source-role').selectOption('');
    await page.locator('#source-status').selectOption('unavailable');
    assert.equal(await page.locator('.source-card').count(),1);
    assert.match(await page.locator('.source-card').innerText(),/robots/);
    await page.locator('#source-status').selectOption('');
    await page.locator('#source-search').fill('Publisher 0');
    assert.equal(await page.locator('.source-card').count(),1);
    await page.locator('[data-source-preview="source-0"]').click();
    await page.waitForFunction(()=>document.querySelector('#source-preview h3')?.textContent==='Publisher 0');
    assert.equal(await page.locator('#source-preview a').count(),1);
    await page.locator('[data-source-poll="source-0"]').click();
    await page.waitForFunction(()=>document.querySelector('#source-directory-feedback').textContent.includes('Poll queued'));
    await page.locator('[data-source-poll-all]').click();
    await page.waitForFunction(()=>document.querySelector('#source-directory-feedback').textContent.includes('3 enabled sources'));
    await page.locator('[data-source-add]').first().click();
    await page.locator('#source-quick-add [name=name]').fill('Independent finance journal');
    await page.locator('#source-quick-add [name=url]').fill('https://journal.example/feed');
    await page.locator('#source-quick-add [name=contentRole]').selectOption('commentary');
    await page.locator('#source-quick-add button').first().click();
    await page.waitForFunction(()=>document.querySelector('#source-directory-feedback').textContent.includes('Feed added'));
    await page.locator('#source-search').fill('Independent');
    assert.match(await page.locator('.source-card').innerText(),/Commentary/);
    await page.locator('#source-search').fill('');
    await page.screenshot({path:path.join(os.tmpdir(),'crawler-sources-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.querySelector('#source-directory').scrollWidth<=document.querySelector('#source-directory').clientWidth+1));
    await page.screenshot({path:path.join(os.tmpdir(),'crawler-sources-mobile.png')});
    await page.locator('[data-source-close]').click();
    assert.ok(await page.locator('#start-query').isVisible());
    await page.locator('[data-open-source-directory]:visible').first().click();
    await page.locator('#source-search').fill('Publisher 0');
    await page.locator('[data-source-edit="source-0"]').click();
    await page.waitForSelector('#research-tools[open]');
    assert.equal(await page.locator('#connector-tool-form [name=url]').inputValue(),'https://publisher.example/feed/0');
    assert.equal(await page.locator('#connector-tool-form [name=id]').inputValue(),'source-0');
    assert.deepEqual(errors,[]);
    console.log('Source directory passed: lazy loading, filters, pagination, contributions, polling, add-feed and mobile.');
  }finally{await browser?.close();child.kill();}
})().catch(e=>{console.error(e);process.exitCode=1;});
